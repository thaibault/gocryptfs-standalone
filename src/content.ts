// region imports
import {
    createCipheriv, createDecipheriv, hkdfSync, randomBytes
} from 'crypto'
import {open} from 'fs/promises'
// endregion
/*
    On-disk layout of a gocryptfs (format version 2) file:

    - Empty plaintext results in an empty file (no header).
    - 18 byte header: 2 byte big endian version (2) and a random 16 byte file
      id.
    - 4096 byte plaintext blocks, each stored as 16 byte nonce, ciphertext and
      16 byte authentication tag (AES-256-GCM). The associated data is the
      big endian 8 byte block number followed by the file id.
*/
export const KEY_LENGTH = 32
export const VERSION = 2
export const VERSION_LENGTH = 2
export const FILE_ID_LENGTH = 16
export const HEADER_LENGTH = VERSION_LENGTH + FILE_ID_LENGTH
export const IV_LENGTH = 16
export const TAG_LENGTH = 16
export const BLOCK_OVERHEAD = IV_LENGTH + TAG_LENGTH
export const PLAIN_BLOCK_SIZE = 4096
export const CIPHER_BLOCK_SIZE = PLAIN_BLOCK_SIZE + BLOCK_OVERHEAD
// "info" values gocryptfs mixes into its hkdf derived keys.
export const KEY_INFORMATION = {content: 'AES-GCM file content encryption'}

const ALL_ZERO_CIPHER_BLOCK = Buffer.alloc(CIPHER_BLOCK_SIZE)

export class CorruptFileError extends Error {
    name = 'CorruptFileError'
}
/**
 * Derives a sub key from given (master) key like gocryptfs does (HKDF-SHA256
 * without salt).
 * @param key - Input key material.
 * @param information - Context string to bind the derived key to.
 * @returns Derived 32 byte key.
 */
export const deriveKey = (key: Buffer, information: string): Buffer =>
    Buffer.from(hkdfSync(
        'sha256', key, Buffer.alloc(0), information, KEY_LENGTH
    ))
/**
 * Derives the file content key from given master key.
 * @param masterKey - Unlocked vault master key.
 * @returns Key to en- and decrypt file content blocks.
 */
export const deriveContentKey = (masterKey: Buffer): Buffer =>
    deriveKey(masterKey, KEY_INFORMATION.content)
/**
 * Builds the associated data authenticated with each block.
 * @param blockNumber - Zero based index of the block inside its file.
 * @param fileID - File id from the file's header (none for the master key).
 * @returns Associated data.
 */
export const getAssociatedData = (
    blockNumber: number, fileID: Buffer | null
): Buffer => {
    const blockNumberBuffer = Buffer.alloc(8)
    blockNumberBuffer.writeBigUInt64BE(BigInt(blockNumber))

    return fileID ?
        Buffer.concat([blockNumberBuffer, fileID]) :
        blockNumberBuffer
}
/**
 * Encrypts one plaintext block.
 * @param key - Content key.
 * @param plaintext - At most "PLAIN_BLOCK_SIZE" bytes.
 * @param blockNumber - Zero based index of the block inside its file.
 * @param fileID - File id from the file's header.
 * @param iv - Nonce to use, a random one will be generated by default.
 * @returns Nonce, ciphertext and authentication tag.
 */
export const encryptBlock = (
    key: Buffer,
    plaintext: Buffer,
    blockNumber: number,
    fileID: Buffer | null,
    iv: Buffer = randomBytes(IV_LENGTH)
): Buffer => {
    if (plaintext.length === 0)
        return plaintext

    const cipher = createCipheriv('aes-256-gcm', key, iv)
    cipher.setAAD(getAssociatedData(blockNumber, fileID))

    return Buffer.concat([
        iv, cipher.update(plaintext), cipher.final(), cipher.getAuthTag()
    ])
}
/**
 * Decrypts and authenticates one ciphertext block.
 * @param key - Content key.
 * @param ciphertext - Nonce, ciphertext and authentication tag.
 * @param blockNumber - Zero based index of the block inside its file.
 * @param fileID - File id from the file's header.
 * @returns Plaintext.
 */
export const decryptBlock = (
    key: Buffer,
    ciphertext: Buffer,
    blockNumber: number,
    fileID: Buffer | null
): Buffer => {
    if (ciphertext.length === 0)
        return ciphertext

    // NOTE: gocryptfs represents file holes as all-zero ciphertext blocks.
    if (ciphertext.equals(ALL_ZERO_CIPHER_BLOCK))
        return Buffer.alloc(PLAIN_BLOCK_SIZE)

    if (ciphertext.length <= BLOCK_OVERHEAD)
        throw new CorruptFileError(
            `Block ${String(blockNumber)} is too short ` +
            `(${String(ciphertext.length)} bytes).`
        )

    const iv = ciphertext.subarray(0, IV_LENGTH)
    if (iv.every((value) => value === 0))
        throw new CorruptFileError(
            `Block ${String(blockNumber)} has an all-zero nonce.`
        )

    const decipher = createDecipheriv('aes-256-gcm', key, iv)
    decipher.setAAD(getAssociatedData(blockNumber, fileID))
    decipher.setAuthTag(ciphertext.subarray(-TAG_LENGTH))

    try {
        return Buffer.concat([
            decipher.update(ciphertext.subarray(IV_LENGTH, -TAG_LENGTH)),
            decipher.final()
        ])
    } catch {
        throw new CorruptFileError(
            `Block ${String(blockNumber)} failed authentication.`
        )
    }
}
/**
 * Creates a new file header with a random file id.
 * @returns Header bytes.
 */
export const createHeader = (): Buffer => {
    const header = Buffer.alloc(HEADER_LENGTH)
    header.writeUInt16BE(VERSION)
    randomBytes(FILE_ID_LENGTH).copy(header, VERSION_LENGTH)

    return header
}
/**
 * Validates given file header and extracts its file id.
 * @param header - First "HEADER_LENGTH" bytes of an encrypted file.
 * @returns File id.
 */
export const parseHeader = (header: Buffer): Buffer => {
    if (header.length !== HEADER_LENGTH)
        throw new CorruptFileError(
            `Header is truncated (${String(header.length)} bytes).`
        )

    const version = header.readUInt16BE()
    if (version !== VERSION)
        throw new CorruptFileError(
            `Unsupported file version ${String(version)}.`
        )

    const fileID = header.subarray(VERSION_LENGTH)
    if (fileID.every((value) => value === 0))
        throw new CorruptFileError('File id is all-zero.')

    return fileID
}
/**
 * Calculates the plaintext size of an encrypted file.
 * @param cipherSize - Size of the encrypted file.
 * @returns Plaintext size.
 */
export const getPlainSize = (cipherSize: number): number => {
    if (cipherSize <= HEADER_LENGTH)
        return 0

    const payloadSize = cipherSize - HEADER_LENGTH
    const fullBlocks = Math.floor(payloadSize / CIPHER_BLOCK_SIZE)
    const rest = payloadSize % CIPHER_BLOCK_SIZE

    return fullBlocks * PLAIN_BLOCK_SIZE +
        (rest > BLOCK_OVERHEAD ? rest - BLOCK_OVERHEAD : 0)
}
/**
 * Calculates the encrypted size of a plaintext file.
 * @param plainSize - Size of the plaintext file.
 * @returns Encrypted size.
 */
export const getCipherSize = (plainSize: number): number => {
    if (plainSize === 0)
        return 0

    const fullBlocks = Math.floor(plainSize / PLAIN_BLOCK_SIZE)
    const rest = plainSize % PLAIN_BLOCK_SIZE

    return HEADER_LENGTH +
        fullBlocks * CIPHER_BLOCK_SIZE +
        (rest > 0 ? rest + BLOCK_OVERHEAD : 0)
}
/**
 * Reads given file in chunks of given size.
 * @param path - File to read.
 * @param chunkSize - Maximal chunk size.
 * @param offset - Position to start reading at.
 * @yields {Buffer} Chunks (only the last one may be shorter than "chunkSize").
 */
const readChunks = async function* (
    path: string, chunkSize: number, offset = 0
): AsyncGenerator<Buffer> {
    const fileHandle = await open(path, 'r')
    try {
        let position = offset
        for (;;) {
            const buffer = Buffer.alloc(chunkSize)
            let length = 0
            // NOTE: A read may return less than requested before EOF.
            while (length < chunkSize) {
                const {bytesRead} = await fileHandle.read(
                    buffer, length, chunkSize - length, position + length
                )
                if (bytesRead === 0)
                    break
                length += bytesRead
            }

            if (length === 0)
                return

            position += length
            yield buffer.subarray(0, length)

            if (length < chunkSize)
                return
        }
    } finally {
        await fileHandle.close()
    }
}
/**
 * Decrypts given encrypted file block by block.
 * @param key - Content key.
 * @param path - Encrypted file.
 * @yields {Buffer} Plaintext blocks.
 */
export const decryptFileContent = async function* (
    key: Buffer, path: string
): AsyncGenerator<Buffer> {
    let fileID: Buffer | null = null
    for await (const header of readChunks(path, HEADER_LENGTH)) {
        fileID = parseHeader(header)
        break
    }
    // Empty file.
    if (!fileID)
        return

    let blockNumber = 0
    for await (
        const block of readChunks(path, CIPHER_BLOCK_SIZE, HEADER_LENGTH)
    ) {
        yield decryptBlock(key, block, blockNumber, fileID)
        blockNumber += 1
    }
}
/**
 * Encrypts given plaintext file block by block.
 * @param key - Content key.
 * @param path - Plaintext file.
 * @yields {Buffer} Header followed by ciphertext blocks (nothing for empty
 * files).
 */
export const encryptFileContent = async function* (
    key: Buffer, path: string
): AsyncGenerator<Buffer> {
    let fileID: Buffer | null = null
    let blockNumber = 0
    for await (const block of readChunks(path, PLAIN_BLOCK_SIZE)) {
        if (!fileID) {
            const header = createHeader()
            fileID = header.subarray(VERSION_LENGTH)
            yield header
        }

        yield encryptBlock(key, block, blockNumber, fileID)
        blockNumber += 1
    }
}
